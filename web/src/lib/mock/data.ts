// assetRef turns an asset id into the asset reference attached to a finding (label
// follows the same precedence as the backend coverageNodeLabel: URL > domain > IP > app name).
// The "By asset" tree hangs findings onto assets via these references.
function assetRef(id: number): FindingAsset {
  const asset = assets.find((candidate) => candidate.id === id);
  if (!asset) throw new Error(`mock assetRef: unknown asset ${id}`);
  return {
    id: String(id),
    type: asset.type,
    label: asset.url || asset.domain || asset.ip || asset.app_name || String(id),
  };
}

